#include "cli.h"

#include <QCommandLineOption>
#include <QCommandLineParser>
#include <QDir>
#include <QFile>
#include <QFileInfo>
#include <QJsonDocument>
#include <QJsonObject>
#include <QUrl>

QString resolveCliPath(const QString &rawArg, const QString &workingDir)
{
    QString path = rawArg.trimmed();
    if (path.isEmpty())
        return {};

    if (path.startsWith(QLatin1String("file://"), Qt::CaseInsensitive)) {
        const QUrl url(path);
        if (url.isLocalFile())
            path = url.toLocalFile();
    }

    if (path == QLatin1String("~")) {
        path = QDir::homePath();
    } else if (path.startsWith(QLatin1String("~/"))) {
        path = QDir::homePath() + path.mid(1);
    }

    if (!QDir::isAbsolutePath(path)) {
        const QDir base(workingDir.isEmpty() ? QDir::currentPath() : workingDir);
        path = base.absoluteFilePath(path);
    }

    return QDir::cleanPath(path);
}

QString generateShellInitScript(const QString &shellName, QString *errorOut)
{
    const QString sh = shellName.trimmed().toLower();
    if (sh == QLatin1String("bash") || sh == QLatin1String("zsh") || sh == QLatin1String("sh")) {
        return QStringLiteral(
            "# TwinForge shell cd-on-exit helper (generated by twinforge --shell-init %1)\n"
            "tfcd() {\n"
            "    local tmp\n"
            "    tmp=\"$(mktemp -t twinforge-cwd.XXXXXX)\" || return 1\n"
            "    twinforge --last-dir-file \"$tmp\" \"$@\"\n"
            "    local rc=$?\n"
            "    if [ -f \"$tmp\" ]; then\n"
            "        local dir\n"
            "        dir=\"$(cat \"$tmp\")\"\n"
            "        rm -f \"$tmp\"\n"
            "        if [ -n \"$dir\" ] && [ -d \"$dir\" ]; then\n"
            "            builtin cd -- \"$dir\" || return 1\n"
            "        fi\n"
            "    fi\n"
            "    return $rc\n"
            "}\n").arg(sh);
    }
    if (sh == QLatin1String("fish")) {
        return QStringLiteral(
            "# TwinForge shell cd-on-exit helper (generated by twinforge --shell-init fish)\n"
            "function tfcd\n"
            "    set -l tmp (mktemp -t twinforge-cwd.XXXXXX)\n"
            "    twinforge --last-dir-file \"$tmp\" $argv\n"
            "    set -l rc $status\n"
            "    if test -f \"$tmp\"\n"
            "        set -l dir (cat \"$tmp\")\n"
            "        rm -f \"$tmp\"\n"
            "        if test -n \"$dir\" -a -d \"$dir\"\n"
            "            builtin cd -- \"$dir\"\n"
            "        end\n"
            "    end\n"
            "    return $rc\n"
            "end\n");
    }

    if (errorOut) {
        *errorOut = QStringLiteral("Unsupported shell '%1'. Supported shells: bash, zsh, fish.")
                        .arg(shellName);
    }
    return {};
}

CliRequest parseCliArguments(const QStringList &arguments,
                             const QString &workingDir,
                             const QString &appVersion,
                             QString *errorOut,
                             bool *shouldExitOk,
                             QString *stdoutOut)
{
    if (errorOut)
        errorOut->clear();
    if (shouldExitOk)
        *shouldExitOk = false;
    if (stdoutOut)
        stdoutOut->clear();

    QCommandLineParser parser;
    parser.setApplicationDescription(
        QStringLiteral("TwinForge — fast, modern dual-panel file manager for Linux."));

    const QCommandLineOption helpOpt = parser.addHelpOption();
    const QCommandLineOption versionOpt = parser.addVersionOption();

    const QCommandLineOption newTabOpt(
        {QStringLiteral("t"), QStringLiteral("new-tab")},
        QStringLiteral("Open given path(s) in new tab(s)."));
    const QCommandLineOption selectOpt(
        {QStringLiteral("s"), QStringLiteral("select")},
        QStringLiteral("Open parent folder and highlight/select the given file or folder."),
        QStringLiteral("path"));
    const QCommandLineOption newWindowOpt(
        {QStringLiteral("n"), QStringLiteral("new-window")},
        QStringLiteral("Launch a new independent window instead of reusing an existing instance."));
    const QCommandLineOption lastDirFileOpt(
        QStringLiteral("last-dir-file"),
        QStringLiteral("Write the active panel's directory to <file> on exit (for shell cd integration)."),
        QStringLiteral("file"));
    const QCommandLineOption printLastDirOpt(
        QStringLiteral("print-last-dir"),
        QStringLiteral("Print the active panel's directory to stdout on exit."));
    const QCommandLineOption shellInitOpt(
        QStringLiteral("shell-init"),
        QStringLiteral("Print shell cd-on-exit helper function (bash, zsh, fish) and exit."),
        QStringLiteral("shell"));
    const QCommandLineOption smokeTestOpt(
        QStringLiteral("smoke-test"),
        QStringLiteral("Run headless packaging self-test (load QML, open archive <left_path>, copy entry into <right_path>) and exit."));

    parser.addOption(newTabOpt);
    parser.addOption(selectOpt);
    parser.addOption(newWindowOpt);
    parser.addOption(lastDirFileOpt);
    parser.addOption(printLastDirOpt);
    parser.addOption(shellInitOpt);
    parser.addOption(smokeTestOpt);

    parser.addPositionalArgument(QStringLiteral("left_path"),
                                 QStringLiteral("Optional directory or file to open in the active/left panel."),
                                 QStringLiteral("[left_path [right_path]]"));

    CliRequest req;
    if (!parser.parse(arguments)) {
        if (errorOut)
            *errorOut = parser.errorText();
        return req;
    }

    if (parser.isSet(helpOpt)) {
        if (shouldExitOk)
            *shouldExitOk = true;
        if (stdoutOut) {
            QString help = parser.helpText();
            help.replace(QLatin1String("Usage: <executable_name> "), QLatin1String("Usage: twinforge "));
            if (help.startsWith(QLatin1String("Usage:  ")))
                help.replace(0, 8, QStringLiteral("Usage: twinforge "));
            else if (help.startsWith(QLatin1String("Usage: [")))
                help.replace(0, 7, QStringLiteral("Usage: twinforge "));
            *stdoutOut = help;
        }
        return req;
    }

    if (parser.isSet(versionOpt)) {
        if (shouldExitOk)
            *shouldExitOk = true;
        if (stdoutOut)
            *stdoutOut = QStringLiteral("twinforge %1\n").arg(appVersion);
        return req;
    }

    if (parser.isSet(shellInitOpt)) {
        const QString shell = parser.value(shellInitOpt);
        QString err;
        const QString script = generateShellInitScript(shell, &err);
        if (!err.isEmpty()) {
            if (errorOut)
                *errorOut = err;
            return req;
        }
        req.shellInit = shell;
        if (shouldExitOk)
            *shouldExitOk = true;
        if (stdoutOut)
            *stdoutOut = script;
        return req;
    }

    req.newTab = parser.isSet(newTabOpt);
    req.newWindow = parser.isSet(newWindowOpt);
    req.printLastDir = parser.isSet(printLastDirOpt);
    req.smokeTest = parser.isSet(smokeTestOpt);

    if (parser.isSet(lastDirFileOpt))
        req.lastDirFile = resolveCliPath(parser.value(lastDirFileOpt), workingDir);

    if (parser.isSet(selectOpt)) {
        const QString resolvedSel = resolveCliPath(parser.value(selectOpt), workingDir);
        if (!resolvedSel.isEmpty()) {
            req.selectPath = resolvedSel;
            const QFileInfo selFi(resolvedSel);
            req.leftPath = selFi.absolutePath();
        }
    }

    const QStringList posArgs = parser.positionalArguments();
    if (posArgs.size() >= 1) {
        const QString p1 = resolveCliPath(posArgs.at(0), workingDir);
        const QFileInfo fi1(p1);
        if (!req.smokeTest && fi1.exists() && fi1.isFile()) {
            req.leftPath = fi1.absolutePath();
            if (req.selectPath.isEmpty())
                req.selectPath = fi1.absoluteFilePath();
        } else if (!p1.isEmpty()) {
            req.leftPath = p1;
        }
    }

    if (posArgs.size() >= 2) {
        const QString p2 = resolveCliPath(posArgs.at(1), workingDir);
        const QFileInfo fi2(p2);
        if (!req.smokeTest && fi2.exists() && fi2.isFile()) {
            req.rightPath = fi2.absolutePath();
            if (req.selectPath.isEmpty())
                req.selectPath = fi2.absoluteFilePath();
        } else if (!p2.isEmpty()) {
            req.rightPath = p2;
        }
    }

    return req;
}

QByteArray serializeCliRequest(const CliRequest &req)
{
    QJsonObject obj;
    obj.insert(QStringLiteral("leftPath"), req.leftPath);
    obj.insert(QStringLiteral("rightPath"), req.rightPath);
    obj.insert(QStringLiteral("selectPath"), req.selectPath);
    obj.insert(QStringLiteral("newTab"), req.newTab);
    obj.insert(QStringLiteral("activate"), req.activate);
    return QJsonDocument(obj).toJson(QJsonDocument::Compact) + '\n';
}

CliRequest deserializeCliRequest(const QByteArray &payload, bool *ok)
{
    if (ok)
        *ok = false;
    CliRequest req;
    QJsonParseError err{};
    const QJsonDocument doc = QJsonDocument::fromJson(payload.trimmed(), &err);
    if (err.error != QJsonParseError::NoError || !doc.isObject())
        return req;

    const QJsonObject obj = doc.object();
    req.leftPath = obj.value(QStringLiteral("leftPath")).toString();
    req.rightPath = obj.value(QStringLiteral("rightPath")).toString();
    req.selectPath = obj.value(QStringLiteral("selectPath")).toString();
    req.newTab = obj.value(QStringLiteral("newTab")).toBool(false);
    req.activate = obj.value(QStringLiteral("activate")).toBool(true);
    if (ok)
        *ok = true;
    return req;
}

bool writeLastDirFile(const QString &filePath, const QString &dirPath)
{
    if (filePath.trimmed().isEmpty() || dirPath.trimmed().isEmpty())
        return false;
    QFileInfo fi(filePath);
    QDir().mkpath(fi.absolutePath());
    QFile f(filePath);
    if (!f.open(QIODevice::WriteOnly | QIODevice::Truncate))
        return false;
    const QByteArray data = dirPath.toUtf8() + '\n';
    return f.write(data) == data.size();
}
